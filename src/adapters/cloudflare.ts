export interface CloudflareAdapterOptions {
  /** Required for records, subject manifests, search projections and job leases. */
  database: D1DatabaseLike;
  storage?: R2BucketLike;
  cache?: KVNamespaceLike;
  vectorize?: VectorizeIndexLike;
  ai?: WorkersAILike;
  queue?: QueueLike<CloudflareQueuedJob>;
  workflow?: WorkflowLike<CloudflareQueuedJob>;
  objects?: DurableObjectNamespaceLike;
  processors?: Readonly<Record<string, CloudflareProcessor>>;
  /** Optional service binding used when no local processor is registered. */
  processor?: { process(ref: string, input: unknown): Promise<unknown> };
  models?: {
    think?: string;
    embedding?: string;
  };
  /** Defaults to five results and may not exceed Vectorize's metadata limit of 50. */
  vectorTopK?: number;
  /**
   * Maps instance refs to an Init subject. The default maps `customer:123` to
   * `customer`; refs without a colon are already subject names.
   */
  subjectFromRef?: (ref: string) => string;
  /** Run the idempotent schema on first use. Disable when Wrangler migrations own it. */
  autoMigrate?: boolean;
  /** Injectable clock for deterministic tests. */
  now?: () => number;
}

