function changes(result: D1ResultLike): number { return result.meta?.changes ?? 0; }
function likePattern(value: string): string { return `%${value.replace(/[\\%_]/g, match => `\\${match}`)}%`; }
function sqlScalar(value: CloudflareScalar): unknown { return typeof value === "boolean" ? Number(value) : value; }
