/**
 * Use this as a Wrangler D1 migration when autoMigrate is false.
 * The tables are shared by every Cloud subject; Init.Delete only removes rows
 * belonging to its subject and never drops these shared tables.
 */
export const CLOUDFLARE_D1_SCHEMA = `
CREATE TABLE IF NOT EXISTS cloud_subjects (
  subject TEXT PRIMARY KEY,
  revision TEXT NOT NULL,
  manifest TEXT NOT NULL,
  updated_at INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS cloud_records (
  ref TEXT PRIMARY KEY,
  subject TEXT NOT NULL,
  payload TEXT NOT NULL,
  expires_at INTEGER,
  version TEXT NOT NULL,
  updated_at INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS cloud_records_subject ON cloud_records(subject);
CREATE TABLE IF NOT EXISTS cloud_objects (
  ref TEXT PRIMARY KEY,
  subject TEXT NOT NULL,
  expires_at INTEGER,
  version TEXT NOT NULL,
  updated_at INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS cloud_objects_subject ON cloud_objects(subject);
CREATE TABLE IF NOT EXISTS cloud_cache_entries (
  ref TEXT PRIMARY KEY,
  subject TEXT NOT NULL,
  version TEXT NOT NULL,
  ephemeral INTEGER NOT NULL,
  updated_at INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS cloud_cache_entries_subject ON cloud_cache_entries(subject);
CREATE TABLE IF NOT EXISTS cloud_search (
  ref TEXT PRIMARY KEY,
  subject TEXT NOT NULL,
  document TEXT NOT NULL,
  fields TEXT NOT NULL,
  expires_at INTEGER,
  version TEXT NOT NULL,
  updated_at INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS cloud_search_subject ON cloud_search(subject);
CREATE TABLE IF NOT EXISTS cloud_tombstones (
  ref TEXT PRIMARY KEY,
  version TEXT NOT NULL,
  deleted_at INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS cloud_jobs (
  idempotency_key TEXT PRIMARY KEY,
  job_id TEXT NOT NULL,
  status TEXT NOT NULL,
  lease_until INTEGER,
  updated_at INTEGER NOT NULL,
  last_error TEXT
);
CREATE UNIQUE INDEX IF NOT EXISTS cloud_jobs_job_id ON cloud_jobs(job_id);
`;

async function sha256(value: string): Promise<string> {
  const digest = await crypto.subtle.digest("SHA-256", new TextEncoder().encode(value));
  return [...new Uint8Array(digest)].map(byte => byte.toString(16).padStart(2, "0")).join("");
}

export class CloudflareProvider extends CloudProvider {
  readonly id: string = "cloudflare";
  readonly services: CloudProviderServices;
  private readonly options: Required<Pick<CloudflareAdapterOptions, "autoMigrate" | "now" | "subjectFromRef" | "vectorTopK">> & CloudflareAdapterOptions;
  private schemaReady?: Promise<void>;

  constructor(options: CloudflareAdapterOptions) {
    super();
    if (!options?.database) throw new TypeError("CloudflareAdapter requires a D1 database binding");
    const vectorTopK = options.vectorTopK ?? 5;
    if (!Number.isInteger(vectorTopK) || vectorTopK < 1 || vectorTopK > MAX_VECTOR_TOP_K) {
      throw new TypeError(`vectorTopK must be an integer from 1 to ${MAX_VECTOR_TOP_K}`);
    }
    this.options = {
      ...options,
      autoMigrate: options.autoMigrate ?? true,
      now: options.now ?? (() => Math.floor(Date.now() / 1000)),
      subjectFromRef: options.subjectFromRef ?? (ref => ref.includes(":") ? ref.slice(0, ref.indexOf(":")) : ref),
      vectorTopK,
    };
    this.services = {
      database: {
        upsert: context => this.databaseUpsert(context),
        get: context => this.databaseGet(context.plan.ir.ref),
        hydrate: context => this.databaseHydrate(context.input as IndexHit[]),
        delete: context => this.databaseDelete(context.plan),
      },
      storage: options.storage ? {
        upsert: context => this.storageUpsert(context),
        get: context => this.storageGet(context.plan.ir.ref),
        hydrate: context => this.storageHydrate(context.input as IndexHit[]),
        delete: context => this.storageDelete(context.plan),
      } : undefined,
      cache: options.cache ? {
        get: context => this.cacheGet(context.plan.ir.ref),
        put: context => this.cachePut(context),
        invalidate: context => this.cacheInvalidate(context.plan.ir.ref),
      } : undefined,
      index: {
        upsert: context => this.searchUpsert(context),
        search: context => this.search(context.plan),
        delete: context => this.indexDelete(context.plan),
        ...(options.vectorize ? {
          upsertVector: (context: StepContext) => this.vectorUpsert(context),
          searchVector: (context: StepContext) => this.vectorSearch(context),
        } : {}),
      },
      mind: options.ai ? {
        think: context => this.options.ai!.run(context.plan.ir.policy.model ?? this.options.models!.think!, context.input),
        embed: context => this.embed(context.input, context.plan.ir.requirements.semantic),
        embedQuery: context => this.embed(context.input, true),
      } : undefined,
      processor: options.processor || Object.keys(options.processors ?? {}).length ? {
        run: async context => {
          const local = this.options.processors?.[context.plan.ir.ref];
          return local ? local(context.input, context) : this.options.processor!.process(context.plan.ir.ref, context.input);
        },
      } : undefined,
      queue: options.queue ? { enqueue: envelope => this.enqueueJob(envelope) } : undefined,
      workflow: options.workflow ? { start: envelope => this.startWorkflowJob(envelope) } : undefined,
      object: options.objects ? { invoke: plan => this.invokeCoordinated(plan) } : undefined,
    };
  }

  capabilities(): CapabilityCatalog {
    const indexActions = ["upsert", "search", "delete"];
    if (this.options.vectorize) indexActions.push("upsertVector", "searchVector");
    const catalog: CapabilityCatalog = {
      database: { actions: ["upsert", "get", "hydrate", "delete"], persistent: true, strong: true, ttl: true, global: true, cheap: true, provisionable: true },
      index: { actions: indexActions, persistent: true, global: true, provisionable: true },
    };
    if (this.options.storage) catalog.storage = { actions: ["upsert", "get", "hydrate", "delete"], persistent: true, strong: true, ttl: true, global: true, cheap: true, provisionable: true };
    if (this.options.cache) catalog.cache = { actions: ["get", "put", "invalidate"], persistent: false, strong: false, ttl: true, minimumTTL: 60, global: true, cheap: true, provisionable: true };
    if (this.options.ai) catalog.mind = { actions: ["think", "embed", "embedQuery"], global: true, provisionable: true };
    if (this.services.processor) catalog.processor = { actions: ["run"], provisionable: true };
    if (this.options.queue) catalog.queue = { actions: ["enqueue"], persistent: true, provisionable: true };
    if (this.options.workflow) catalog.workflow = { actions: ["start"], persistent: true, provisionable: true };
    if (this.options.objects) catalog.object = { actions: ["invoke"], persistent: true, strong: true, provisionable: true };
    return catalog;
  }

  protected validateProviderPlan(plan: CloudPlan): void {
    const { ir } = plan;
    if (ir.requirements.lifetime !== null && (!Number.isInteger(ir.requirements.lifetime) || ir.requirements.lifetime < 1)) {
      throw new TypeError("Cloudflare TTL must be a positive whole number of seconds");
    }
    if (ir.operation === "think" && !ir.policy.model && !this.options.models?.think) throw new Error("Think requires policy.model or models.think");
    if (ir.operation === "process" && !this.options.processors?.[ir.ref] && !this.options.processor) throw new Error(`Unknown processor: ${ir.ref}`);
    if (plan.required.includes("mind") && !this.options.ai) throw new Error("Workers AI binding is required");
    if (fieldsEnabled(ir.requirements.semantic) && !this.options.vectorize) throw new Error("Semantic intent requires a Vectorize binding");
    if (ir.shape.kind === "blob" && plan.required.includes("storage") && !this.options.storage) throw new Error("Blob persistence requires an R2 binding");
    if (plan.route === "queue" && !this.options.queue) throw new Error("Deferred execution requires a Queue producer binding");
    if (plan.route === "workflow" && !this.options.workflow) throw new Error("Workflow execution requires a Workflow binding");
    if ((ir.objectID || ir.operation === "object") && !this.options.objects) throw new Error("Object coordination requires a Durable Object binding");
    if (new TextEncoder().encode(ir.ref).length > 440 && plan.required.includes("cache")) throw new Error("Ref is too long for a Workers KV key");
    if (ir.mode === "init") {
      const before = plan.observation?.state as StoredManifest | null | undefined;
      if (ir.operation === "delete" && before) {
        if (before.required.includes("cache") && !this.options.cache) throw new Error("Deleting this subject requires its KV binding");
        if (before.required.includes("storage") && !this.options.storage) throw new Error("Deleting this subject requires its R2 binding");
        if (fieldsEnabled(before.policy.semantic) && !this.options.vectorize) {
          throw new Error("Deleting this subject requires its Vectorize binding");
        }
      } else if (ir.operation !== "read" && before) {
        const desired = this.manifestFor(ir, plan.required);
        if (stableJSON(before) !== stableJSON(desired)) {
          throw new Error("CloudflareAdapter does not perform in-place subject migrations; migrate data explicitly or apply Init.Delete before the new contract");
        }
      }
    }
  }

  async describe(ref: string): Promise<SubjectDescription | undefined> {
    await this.ensureSchema();
    const subject = this.options.subjectFromRef(ref);
    const row = await this.options.database.prepare("SELECT manifest FROM cloud_subjects WHERE subject = ?1").bind(subject).first<{ manifest: string }>();
    if (!row) return undefined;
    const manifest = JSON.parse(row.manifest) as StoredManifest;
    return { shape: manifest.shape, policy: manifest.policy };
  }

  async inspect(ir: CloudIR): Promise<Observation> {
    await this.ensureSchema();
    const row = await this.readManifest(ir.ref);
    return row ? { revision: row.revision, state: JSON.parse(row.manifest) as StoredManifest } : { state: null };
  }

  async diff(ir: CloudIR, required: readonly Capability[], current: Observation): Promise<readonly InitChange[]> {
    const before = current.state as StoredManifest | null;
    if (ir.operation === "delete") {
      if (!before) return [{ capability: "database", action: "noop", before: null, after: null }];
      return before.required.map(capability => ({ capability, action: "delete", before, destructive: true }));
    }
    const after = this.manifestFor(ir, required);
    if (!before) return required.map(capability => ({ capability, action: "create", after }));
    const all = [...new Set([...before.required, ...required])];
    const identical = stableJSON(before) === stableJSON(after);
    return all.map(capability => {
      const existed = before.required.includes(capability);
      const desired = required.includes(capability);
      if (identical && existed && desired) return { capability, action: "noop", before, after };
      if (!desired) return { capability, action: "delete", before, after, destructive: true };
      return { capability, action: existed ? "modify" : "create", before, after };
    });
  }

  async reconcile(plan: CloudPlan): Promise<unknown> {
    await this.ensureSchema();
    if (plan.ir.mode !== "init" || !plan.observation || !plan.changes) throw new Error("reconcile requires an inspected init plan");
    if (plan.changes.every(change => change.action === "noop")) return plan.observation.state;
    if (plan.ir.operation === "delete") return this.deleteSubject(plan);
    const manifest = this.manifestFor(plan.ir, plan.required);
    const revision = crypto.randomUUID();
    const now = this.options.now();
    if (plan.observation.revision) {
      const result = await this.options.database.prepare(
        "UPDATE cloud_subjects SET revision = ?1, manifest = ?2, updated_at = ?3 WHERE subject = ?4 AND revision = ?5",
      ).bind(revision, JSON.stringify(manifest), now, plan.ir.ref, plan.observation.revision).run();
      if (changes(result) !== 1) throw new Error("Cloud subject changed after inspection; create a new plan");
    } else {
      try {
        await this.options.database.prepare(
          "INSERT INTO cloud_subjects(subject, revision, manifest, updated_at) VALUES (?1, ?2, ?3, ?4)",
        ).bind(plan.ir.ref, revision, JSON.stringify(manifest), now).run();
      } catch (error) {
        throw new Error("Cloud subject was created after inspection; create a new plan", { cause: error });
      }
    }
    return { revision, state: manifest } satisfies Observation;
  }

  protected async beforeExecute(): Promise<void> {
    await this.ensureSchema();
  }

  private async enqueueJob(envelope: JobEnvelope): Promise<{ jobID: string }> {
    await this.ensureSchema();
    const jobID = `q_${(await sha256(envelope.idempotencyKey)).slice(0, 40)}`;
    const now = this.options.now();
    await this.options.database.prepare(
      "INSERT OR IGNORE INTO cloud_jobs(idempotency_key, job_id, status, lease_until, updated_at) VALUES (?1, ?2, 'queued', NULL, ?3)",
    ).bind(envelope.idempotencyKey, jobID, now).run();
    await this.options.queue!.send({
      version: 1,
      jobID,
      idempotencyKey: envelope.idempotencyKey,
      payload: await encodeValue(envelope),
    }, { contentType: "json" });
    return { jobID };
  }

  private async startWorkflowJob(envelope: JobEnvelope): Promise<{ jobID: string }> {
    const jobID = `w_${(await sha256(envelope.idempotencyKey)).slice(0, 40)}`;
    const job: CloudflareQueuedJob = {
      version: 1,
      jobID,
      idempotencyKey: envelope.idempotencyKey,
      payload: await encodeValue(envelope),
    };
    try {
      const instance = await this.options.workflow!.create({ id: jobID, params: job });
      return { jobID: instance.id || jobID };
    } catch (error) {
      // A repeated idempotency key may race or refer to an already-created run.
      // The deterministic ID is still the durable receipt for that same work.
      if (isAlreadyExists(error)) return { jobID };
      throw error;
    }
  }

  private invokeCoordinated(plan: CloudPlan): Promise<unknown> {
    if (!plan.ir.objectID) throw new Error("Object plan has no identity");
    return this.options.objects!.getByName(plan.ir.objectID).run(plan);
  }

  /** Called by consumeCloudflareQueue; public for custom Queue consumers. */
  async claimJob(job: CloudflareQueuedJob): Promise<"claimed" | "complete" | "busy"> {
    await this.ensureSchema();
    const row = await this.options.database.prepare(
      "SELECT status, lease_until FROM cloud_jobs WHERE idempotency_key = ?1 AND job_id = ?2",
    ).bind(job.idempotencyKey, job.jobID).first<JobRow>();
    if (row?.status === "complete") return "complete";
    const now = this.options.now();
    if (row?.status === "running" && (row.lease_until ?? 0) > now) return "busy";
    if (!row) {
      await this.options.database.prepare(
        "INSERT OR IGNORE INTO cloud_jobs(idempotency_key, job_id, status, lease_until, updated_at) VALUES (?1, ?2, 'queued', NULL, ?3)",
      ).bind(job.idempotencyKey, job.jobID, now).run();
    }
    const result = await this.options.database.prepare(
      "UPDATE cloud_jobs SET status = 'running', lease_until = ?1, updated_at = ?2, last_error = NULL WHERE idempotency_key = ?3 AND job_id = ?4 AND (status IN ('queued', 'failed') OR (status = 'running' AND COALESCE(lease_until, 0) <= ?2))",
    ).bind(now + JOB_LEASE_SECONDS, now, job.idempotencyKey, job.jobID).run();
    return changes(result) === 1 ? "claimed" : "busy";
  }

  async completeJob(job: CloudflareQueuedJob): Promise<void> {
    await this.options.database.prepare(
      "UPDATE cloud_jobs SET status = 'complete', lease_until = NULL, updated_at = ?1, last_error = NULL WHERE idempotency_key = ?2 AND job_id = ?3",
    ).bind(this.options.now(), job.idempotencyKey, job.jobID).run();
  }

  async failJob(job: CloudflareQueuedJob, error: unknown): Promise<void> {
    await this.options.database.prepare(
      "UPDATE cloud_jobs SET status = 'failed', lease_until = NULL, updated_at = ?1, last_error = ?2 WHERE idempotency_key = ?3 AND job_id = ?4",
    ).bind(this.options.now(), String(error).slice(0, 2000), job.idempotencyKey, job.jobID).run();
  }

  private async ensureSchema(): Promise<void> {
    if (!this.options.autoMigrate) return;
    this.schemaReady ??= this.options.database.exec(CLOUDFLARE_D1_SCHEMA).then(() => undefined).catch(error => {
      this.schemaReady = undefined;
      throw error;
    });
    await this.schemaReady;
  }

  private manifestFor(ir: CloudIR, required: readonly Capability[]): StoredManifest {
    return { version: 1, subject: ir.ref, shape: ir.shape, policy: retainedPolicy(ir.policy), required: [...required] };
  }

  private readManifest(subject: string): Promise<ManifestRow | null> {
    return this.options.database.prepare("SELECT revision, manifest FROM cloud_subjects WHERE subject = ?1").bind(subject).first<ManifestRow>();
  }

  private async databaseUpsert(context: StepContext): Promise<AuthorityResult> {
    const { plan, input } = context;
    const now = this.options.now();
    const expiresAt = expiration(now, plan.ir.requirements.lifetime);
    await this.options.database.prepare(
      `INSERT INTO cloud_records(ref, subject, payload, expires_at, version, updated_at)
       VALUES (?1, ?2, ?3, ?4, ?5, ?6)
       ON CONFLICT(ref) DO UPDATE SET subject = excluded.subject, payload = excluded.payload,
       expires_at = excluded.expires_at, version = excluded.version, updated_at = excluded.updated_at`,
    ).bind(plan.ir.ref, this.options.subjectFromRef(plan.ir.ref), await encodeValue(input), expiresAt, plan.id, now).run();
    await this.options.database.prepare("DELETE FROM cloud_tombstones WHERE ref = ?1").bind(plan.ir.ref).run();
    return { kind: "authority", hit: true, value: input, version: plan.id, expiresAt };
  }

  private async databaseGet(ref: string): Promise<AuthorityResult> {
    const row = await this.options.database.prepare(
      "SELECT payload, expires_at, version FROM cloud_records WHERE ref = ?1",
    ).bind(ref).first<PayloadRow>();
    if (!row) return { kind: "authority", hit: false, expiresAt: null };
    if (isExpired(row.expires_at, this.options.now())) {
      await this.options.database.prepare("DELETE FROM cloud_records WHERE ref = ?1 AND version = ?2").bind(ref, row.version).run();
      return { kind: "authority", hit: false, expiresAt: row.expires_at };
    }
    return { kind: "authority", hit: true, value: decodeValue(row.payload), version: row.version, expiresAt: row.expires_at };
  }

  private async databaseHydrate(hits: IndexHit[]): Promise<unknown[]> {
    if (!Array.isArray(hits) || !hits.length) return [];
    const values = await Promise.all(hits.map(hit => this.databaseGet(hit.ref)));
    return values.filter(value => value.hit).map(value => value.value);
  }

  private async databaseDelete(plan: CloudPlan): Promise<void> {
    const now = this.options.now();
    await this.options.database.prepare(
      `INSERT INTO cloud_tombstones(ref, version, deleted_at) VALUES (?1, ?2, ?3)
       ON CONFLICT(ref) DO UPDATE SET version = excluded.version, deleted_at = excluded.deleted_at`,
    ).bind(plan.ir.ref, plan.id, now).run();
    await this.options.database.prepare("DELETE FROM cloud_records WHERE ref = ?1").bind(plan.ir.ref).run();
  }

  private async storageUpsert(context: StepContext): Promise<AuthorityResult> {
    const value = context.input;
    let body: ArrayBuffer | ArrayBufferView | Blob;
    let kind = "arraybuffer";
    let contentType: string | undefined;
    if (value instanceof ArrayBuffer || ArrayBuffer.isView(value)) body = value;
    else if (typeof Blob !== "undefined" && value instanceof Blob) {
      body = value;
      kind = "blob";
      contentType = value.type || undefined;
    } else throw new TypeError("R2 storage only accepts Blob, ArrayBuffer, or an ArrayBuffer view");
    const { plan } = context;
    const now = this.options.now();
    const expiresAt = expiration(now, plan.ir.requirements.lifetime);
    await this.options.storage!.put(this.objectKey(plan.ir.ref), body, {
      customMetadata: {
        "cloud-kind": kind,
        "cloud-version": plan.id,
        ...(contentType ? { "cloud-mime": contentType } : {}),
        ...(expiresAt === null ? {} : { "cloud-expires-at": String(expiresAt) }),
      },
      httpMetadata: { contentType },
    });
    await this.options.database.prepare(
      `INSERT INTO cloud_objects(ref, subject, expires_at, version, updated_at)
       VALUES (?1, ?2, ?3, ?4, ?5)
       ON CONFLICT(ref) DO UPDATE SET subject = excluded.subject, expires_at = excluded.expires_at,
       version = excluded.version, updated_at = excluded.updated_at`,
    ).bind(plan.ir.ref, this.options.subjectFromRef(plan.ir.ref), expiresAt, plan.id, now).run();
    await this.options.database.prepare("DELETE FROM cloud_tombstones WHERE ref = ?1").bind(plan.ir.ref).run();
    return { kind: "authority", hit: true, value, version: plan.id, expiresAt };
  }

  private async storageGet(ref: string): Promise<AuthorityResult> {
    const object = await this.options.storage!.get(this.objectKey(ref));
    if (!object) return { kind: "authority", hit: false, expiresAt: null };
    const expiry = object.customMetadata?.["cloud-expires-at"];
    const expiresAt = expiry === undefined ? null : Number(expiry);
    if (isExpired(expiresAt, this.options.now())) {
      // Do not delete by key here: another writer may already have replaced it.
      return { kind: "authority", hit: false, expiresAt };
    }
    const buffer = await object.arrayBuffer();
    const value = object.customMetadata?.["cloud-kind"] === "blob"
      ? new Blob([buffer], { type: object.customMetadata?.["cloud-mime"] })
      : buffer;
    return { kind: "authority", hit: true, value, version: object.customMetadata?.["cloud-version"], expiresAt };
  }

  private async storageHydrate(hits: IndexHit[]): Promise<unknown[]> {
    if (!Array.isArray(hits)) return [];
    const values = await Promise.all(hits.map(hit => this.storageGet(hit.ref)));
    return values.filter(value => value.hit).map(value => value.value);
  }

  private async storageDelete(plan: CloudPlan): Promise<void> {
    const now = this.options.now();
    await this.options.database.prepare(
      `INSERT INTO cloud_tombstones(ref, version, deleted_at) VALUES (?1, ?2, ?3)
       ON CONFLICT(ref) DO UPDATE SET version = excluded.version, deleted_at = excluded.deleted_at`,
    ).bind(plan.ir.ref, plan.id, now).run();
    await this.options.storage!.delete(this.objectKey(plan.ir.ref));
    await this.options.database.prepare("DELETE FROM cloud_objects WHERE ref = ?1").bind(plan.ir.ref).run();
  }

  private async cacheGet(ref: string): Promise<CacheEntry> {
    const encoded = await this.options.cache!.get(this.cacheKey(ref), "text");
    if (encoded === null) return { hit: false };
    let entry: { version: string; payload: string; expiresAt?: number | null };
    try {
      entry = JSON.parse(encoded) as typeof entry;
      if (!entry || typeof entry.version !== "string" || typeof entry.payload !== "string") throw new Error("invalid cache envelope");
    } catch {
      await this.options.cache!.delete(this.cacheKey(ref));
      return { hit: false };
    }
    if (isExpired(entry.expiresAt ?? null, this.options.now())) return { hit: false };
    const version = await this.currentAuthorityVersion(ref);
    if (version !== entry.version) return { hit: false };
    return { hit: true, value: decodeValue(entry.payload), stale: true };
  }

  private async cachePut(context: StepContext): Promise<void> {
    const { plan, input: value, authority } = context;
    const persistent = plan.ir.requirements.durability === "persistent";
    // Version and expiry belong to the value that was read/committed, never to
    // a later lookup which could observe a different concurrent write.
    if (persistent && (!authority?.hit || !authority.version)) return;
    const version = persistent ? authority!.version! : plan.id;
    const now = this.options.now();
    const requestedExpiry = expiration(now, plan.ir.requirements.lifetime);
    const expiresAt = persistent && authority!.expiresAt !== null
      ? Math.min(authority!.expiresAt, requestedExpiry ?? Infinity) : requestedExpiry;
    if (isExpired(expiresAt, now)) return;
    const encoded = JSON.stringify({ version, expiresAt, payload: await encodeValue(value) });
    await this.options.cache!.put(this.cacheKey(plan.ir.ref), encoded, expiresAt === null ? undefined : {
      // KV requires >=60 seconds physically; the envelope enforces shorter
      // remaining lifetimes without extending the authoritative record's TTL.
      expirationTtl: Math.max(60, Math.ceil(expiresAt - now)),
    });
    await this.options.database.prepare(
      `INSERT INTO cloud_cache_entries(ref, subject, version, ephemeral, updated_at) VALUES (?1, ?2, ?3, ?4, ?5)
       ON CONFLICT(ref) DO UPDATE SET subject = excluded.subject, version = excluded.version,
       ephemeral = excluded.ephemeral, updated_at = excluded.updated_at`,
    ).bind(plan.ir.ref, this.options.subjectFromRef(plan.ir.ref), version, Number(!persistent), now).run();
  }

  private async cacheInvalidate(ref: string): Promise<void> {
    await this.options.database.prepare("DELETE FROM cloud_cache_entries WHERE ref = ?1").bind(ref).run();
    await this.options.cache!.delete(this.cacheKey(ref));
  }

  private async searchUpsert(context: StepContext): Promise<void> {
    const { plan, input } = context;
    if (!await this.authorityHasVersion(plan.ir.ref, plan.id, plan.ir.shape.kind === "blob")) return;
    const fields = selectedFields(input, plan.ir.requirements.searchable);
    const now = this.options.now();
    await this.options.database.prepare(
      `INSERT INTO cloud_search(ref, subject, document, fields, expires_at, version, updated_at)
       VALUES (?1, ?2, ?3, ?4, ?5, ?6, ?7)
       ON CONFLICT(ref) DO UPDATE SET subject = excluded.subject, document = excluded.document,
       fields = excluded.fields, expires_at = excluded.expires_at, version = excluded.version,
       updated_at = excluded.updated_at`,
    ).bind(plan.ir.ref, this.options.subjectFromRef(plan.ir.ref), textFor(input, plan.ir.requirements.searchable), JSON.stringify(fields), expiration(now, plan.ir.requirements.lifetime), plan.id, now).run();
  }

  private async search(plan: CloudPlan): Promise<IndexHit[]> {
    const query = normalizeSearchQuery(plan.ir.policy.query);
    const clauses = ["subject = ?", "(expires_at IS NULL OR expires_at > ?)"];
    const bindings: unknown[] = [this.options.subjectFromRef(plan.ir.ref), this.options.now()];
    if (query.text) {
      clauses.push("document LIKE ? ESCAPE '\\'");
      bindings.push(likePattern(query.text));
    }
    for (const [field, value] of Object.entries(query.where)) {
      clauses.push("json_extract(fields, ?) IS ?");
      bindings.push(`$.${JSON.stringify(field)}`, sqlScalar(value));
    }
    bindings.push(query.limit);
    const result = await this.options.database.prepare(
      `SELECT ref FROM cloud_search WHERE ${clauses.join(" AND ")} ORDER BY updated_at DESC LIMIT ?`,
    ).bind(...bindings).all<RefRow>();
    return (result.results ?? []).map(row => ({ ref: row.ref }));
  }

  private async embed(input: unknown, fields: Fields): Promise<number[]> {
    const text = typeof input === "string" ? input : textFor(input, fields);
    if (!text) throw new TypeError("No text was selected for embedding");
    const response = await this.options.ai!.run(this.options.models?.embedding ?? EMBEDDING_MODEL, { text: [text] }) as { data?: unknown[] };
    const vector = response?.data?.[0];
    if (!Array.isArray(vector) || !vector.every(value => typeof value === "number" && Number.isFinite(value))) {
      throw new Error("Workers AI embedding model returned no numeric vector");
    }
    return vector as number[];
  }

  private async vectorUpsert(context: StepContext): Promise<void> {
    const values = context.input as number[];
    const { plan } = context;
    if (!Array.isArray(values) || !values.length) throw new TypeError("Vectorize upsert requires an embedding vector");
    if (!await this.authorityHasVersion(plan.ir.ref, plan.id, plan.ir.shape.kind === "blob")) return;
    await this.options.vectorize!.upsert([{
      id: await this.vectorID(plan.ir.ref),
      values,
      namespace: await this.vectorNamespace(this.options.subjectFromRef(plan.ir.ref)),
      metadata: { ref: plan.ir.ref, version: plan.id },
    }]);
  }

  private async vectorSearch(context: StepContext): Promise<IndexHit[]> {
    const result = await this.options.vectorize!.query(context.input as number[], {
      topK: this.options.vectorTopK,
      namespace: await this.vectorNamespace(this.options.subjectFromRef(context.plan.ir.ref)),
      returnMetadata: "all",
    });
    return result.matches.flatMap(match => typeof match.metadata?.ref === "string" ? [{ ref: match.metadata.ref, score: match.score }] : []);
  }

  private async indexDelete(plan: CloudPlan): Promise<void> {
    if (!await this.deleteIsCurrent(plan.ir.ref, plan.id)) return;
    await this.options.database.prepare("DELETE FROM cloud_search WHERE ref = ?1").bind(plan.ir.ref).run();
    if (this.options.vectorize) await this.options.vectorize.deleteByIds([await this.vectorID(plan.ir.ref)]);
  }

  private async authorityHasVersion(ref: string, version: string, blob: boolean): Promise<boolean> {
    if (blob) {
      const object = await this.options.storage!.head(this.objectKey(ref));
      return object?.customMetadata?.["cloud-version"] === version;
    }
    const row = await this.options.database.prepare("SELECT version FROM cloud_records WHERE ref = ?1").bind(ref).first<VersionRow>();
    return row?.version === version;
  }

  private async deleteIsCurrent(ref: string, version: string): Promise<boolean> {
    const record = await this.options.database.prepare("SELECT version FROM cloud_records WHERE ref = ?1").bind(ref).first<VersionRow>();
    const object = await this.options.database.prepare("SELECT version FROM cloud_objects WHERE ref = ?1").bind(ref).first<VersionRow>();
    if (record || object) return false;
    const tombstone = await this.options.database.prepare("SELECT version FROM cloud_tombstones WHERE ref = ?1").bind(ref).first<VersionRow>();
    return tombstone?.version === version;
  }

  private async currentAuthorityVersion(ref: string): Promise<string | undefined> {
    const now = this.options.now();
    const [record, object, cache] = await Promise.all([
      this.options.database.prepare("SELECT version FROM cloud_records WHERE ref = ?1 AND (expires_at IS NULL OR expires_at > ?2)").bind(ref, now).first<VersionRow>(),
      this.options.database.prepare("SELECT version FROM cloud_objects WHERE ref = ?1 AND (expires_at IS NULL OR expires_at > ?2)").bind(ref, now).first<VersionRow>(),
      this.options.database.prepare("SELECT version, ephemeral FROM cloud_cache_entries WHERE ref = ?1").bind(ref).first<CacheVersionRow>(),
    ]);
    return record?.version ?? object?.version ?? (cache?.ephemeral ? cache.version : undefined);
  }

  private async deleteSubject(plan: CloudPlan): Promise<Observation> {
    const current = await this.readManifest(plan.ir.ref);
    if (current && current.revision !== plan.observation!.revision) throw new Error("Cloud subject changed after inspection; create a new plan");
    if (current) {
      const result = await this.options.database.prepare("DELETE FROM cloud_subjects WHERE subject = ?1 AND revision = ?2").bind(plan.ir.ref, current.revision).run();
      if (changes(result) !== 1) throw new Error("Cloud subject changed after inspection; create a new plan");
    }
    const recordRows = await this.options.database.prepare("SELECT ref FROM cloud_records WHERE subject = ?1").bind(plan.ir.ref).all<RefRow>();
    const objectRows = await this.options.database.prepare("SELECT ref FROM cloud_objects WHERE subject = ?1").bind(plan.ir.ref).all<RefRow>();
    const cacheRows = await this.options.database.prepare("SELECT ref FROM cloud_cache_entries WHERE subject = ?1").bind(plan.ir.ref).all<RefRow>();
    const refs = [...new Set([...(recordRows.results ?? []), ...(objectRows.results ?? []), ...(cacheRows.results ?? [])].map(row => row.ref))];
    if (this.options.cache) await Promise.all(refs.map(ref => this.options.cache!.delete(this.cacheKey(ref))));
    if (this.options.storage && objectRows.results?.length) await this.options.storage.delete(objectRows.results.map(row => this.objectKey(row.ref)));
    if (this.options.vectorize) {
      for (let offset = 0; offset < refs.length; offset += 1000) {
        await this.options.vectorize.deleteByIds(await Promise.all(refs.slice(offset, offset + 1000).map(ref => this.vectorID(ref))));
      }
    }
    await this.options.database.prepare("DELETE FROM cloud_search WHERE subject = ?1").bind(plan.ir.ref).run();
    await this.options.database.prepare("DELETE FROM cloud_records WHERE subject = ?1").bind(plan.ir.ref).run();
    await this.options.database.prepare("DELETE FROM cloud_objects WHERE subject = ?1").bind(plan.ir.ref).run();
    await this.options.database.prepare("DELETE FROM cloud_cache_entries WHERE subject = ?1").bind(plan.ir.ref).run();
    return { state: null };
  }

  private objectKey(ref: string): string { return `cloud/${encodeURIComponent(ref)}`; }
  private cacheKey(ref: string): string { return `cloud:${ref}`; }
  private vectorID(ref: string): Promise<string> { return sha256(`ref:${ref}`); }
  private async vectorNamespace(subject: string): Promise<string> {
    return new TextEncoder().encode(subject).length <= 64 ? subject : (await sha256(`subject:${subject}`)).slice(0, 64);
  }
}

/** Capability names at the composition boundary, mapped to Worker bindings. */
export interface CloudflareConnectorBindings {
  database: D1DatabaseLike;
  cache?: KVNamespaceLike;
  storage?: R2BucketLike;
  index?: VectorizeIndexLike;
  mind?: WorkersAILike;
  processor?: CloudflareAdapterOptions["processor"];
  queue?: QueueLike<CloudflareQueuedJob>;
  workflow?: WorkflowLike<CloudflareQueuedJob>;
  object?: DurableObjectNamespaceLike;
}
export type CloudflareProviderOptions = Omit<CloudflareAdapterOptions,
  "database" | "cache" | "storage" | "vectorize" | "ai" | "processor" | "queue" | "workflow" | "objects">;

export function createCloudflareProvider(
  bindings: CloudflareConnectorBindings,
  options: CloudflareProviderOptions = {},
): CloudflareProvider {
  const { index, mind, object, ...rest } = bindings;
  return new CloudflareProvider({ ...options, ...rest, vectorize: index, ai: mind, objects: object });
}

/** Queue consumer with D1-backed leases and durable idempotency. */
export async function consumeCloudflareQueue(
  cloud: CloudC,
  adapter: CloudflareProvider,
  batch: CloudflareQueueBatch,
): Promise<void> {
  await Promise.all(batch.messages.map(async message => {
    const job = message.body;
    if (!job || job.version !== 1 || typeof job.jobID !== "string" || typeof job.idempotencyKey !== "string" || typeof job.payload !== "string") {
      message.ack();
      return;
    }
    let envelope: JobEnvelope;
    try {
      envelope = decodeValue(job.payload) as JobEnvelope;
      if (!envelope || envelope.version !== 1 || envelope.idempotencyKey !== job.idempotencyKey) throw new Error("Invalid job envelope");
    } catch {
      message.ack();
      return;
    }
    const state = await adapter.claimJob(job);
    if (state === "complete") { message.ack(); return; }
    if (state === "busy") { message.retry({ delaySeconds: 30 }); return; }
    try {
      await cloud.Resume(envelope);
      await adapter.completeJob(job);
      message.ack();
    } catch (error) {
      await adapter.failJob(job, error);
      message.retry();
    }
  }));
}

/** Workflow entry point: pass the Workflow event payload to this function. */
export async function resumeCloudflareWorkflow(cloud: CloudC, job: CloudflareQueuedJob): Promise<unknown> {
  if (!job || job.version !== 1 || typeof job.payload !== "string") throw new Error("Unsupported Cloud workflow payload");
  const envelope = decodeValue(job.payload) as JobEnvelope;
  if (!envelope || envelope.version !== 1 || envelope.idempotencyKey !== job.idempotencyKey) throw new Error("Unsupported Cloud workflow payload");
  return cloud.Resume(envelope);
}

/** RPC method body; the caller must serialize calls within its Durable Object. */
export function runCloudflareObject(cloud: CloudC, plan: CloudPlan): Promise<unknown> {
  if (!plan.ir.objectID) throw new Error("Object plan has no identity");
  return cloud.Apply(clonePlanWithoutObject(plan));
}

/** Create ONCE per Durable Object instance, not once per RPC/request. */
export function createCloudflareObjectRunner(cloud: CloudC): (plan: CloudPlan) => Promise<unknown> {
  let pending: Promise<unknown> = Promise.resolve();
  return plan => {
    const next = pending.then(() => runCloudflareObject(cloud, plan));
    pending = next.catch(() => undefined);
    return next;
  };
}

function isAlreadyExists(error: unknown): boolean {
  const message = String(error).toLowerCase();
  return message.includes("already exists") || message.includes("duplicate") || message.includes("conflict");
}

